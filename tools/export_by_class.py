"""Re-group identified (non-FUN_) functions from the Ghidra export into one file per class/namespace.

Group key, in order: `Namespace::` prefix (templates stripped), else the text before the first `_`
(`CBasicReview_SelectComments` -> CBasicReview), else `_misc`. Functions still named FUN_xxxxxxxx are skipped
(--include-unnamed puts them in `_unnamed`). Renames from <repo>/renames.csv are applied and their evidence is
written above each function. Also writes INDEX.md (group -> function count) and index.csv (function -> file).

The output is decompiler text derived from the game: it is gitignored by default (see .gitignore: identified/).

Usage: python export_by_class.py [--repo PATH] [--out DIR] [--include-unnamed]
"""
import argparse
import csv
import os
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
import re
import sys
from collections import defaultdict

HDR = re.compile(r'^//// FUNCTION (.+?) @ ([0-9a-fA-F]+) ////$')
TEMPLATE = re.compile(r'<[^<>]*>')
UNNAMED = re.compile(r'^FUN_[0-9a-fA-F]{8}$')


def group_of(name):
    prev = None
    while prev != name:
        prev, name = name, TEMPLATE.sub('', name)
    name = name.lstrip('~')
    if '::' in name:
        head = name.split('::')[0]
    elif '_' in name.strip('_'):
        head = name.strip('_').split('_')[0]
    else:
        head = ''
    head = re.sub(r'[^A-Za-z0-9]', '', head)
    return head or '_misc'


def load_renames(repo):
    out = {}
    path = os.path.join(repo, 'renames.csv')
    if os.path.exists(path):
        for r in csv.DictReader(open(path, newline='', encoding='utf-8', errors='ignore')):
            out[r['old_name']] = (r['new_name'], r.get('evidence', ''))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--repo', default=REPO_ROOT)
    ap.add_argument('--out', default=os.path.join(REPO_ROOT, 'data', 'identified'))
    ap.add_argument('--include-unnamed', action='store_true')
    a = ap.parse_args()

    exp = os.path.join(a.repo, 'data', 'ExportDecompiled')
    renames = load_renames(a.repo)
    groups = defaultdict(list)       # group -> [(addr, name, evidence, lines)]
    for fn in sorted(f for f in os.listdir(exp) if f.startswith('decomp_') and f.endswith('.c')):
        cur, buf = None, []
        def flush():
            if cur:
                groups[cur[3]].append((cur[1], cur[0], cur[2], buf))
        for line in open(os.path.join(exp, fn), encoding='utf-8', errors='ignore'):
            line = line.rstrip('\n')
            m = HDR.match(line)
            if m:
                flush()
                name, addr = m.group(1), m.group(2).lower()
                ev = ''
                if name in renames:
                    name, ev = renames[name]
                if UNNAMED.match(name) and not a.include_unnamed:
                    cur, buf = None, []
                    continue
                g = '_unnamed' if UNNAMED.match(name) else group_of(name)
                cur, buf = (name, addr, ev, g), []
            elif cur:
                buf.append(line)
        flush()

    os.makedirs(a.out, exist_ok=True)
    index = []
    for g, items in sorted(groups.items()):
        items.sort()
        with open(os.path.join(a.out, g + '.c'), 'w', encoding='utf-8', newline='\n') as f:
            f.write('/* %s - %d functions, sorted by address. Generated by tools/export_by_class.py */\n\n' % (g, len(items)))
            for addr, name, ev, body in items:
                f.write('/* %s @ %s%s */\n' % (name, addr, (' - evidence: ' + ev.replace('*/', '* /')) if ev else ''))
                f.write('\n'.join(body).strip('\n') + '\n\n')
                index.append((name, addr, g + '.c'))
    with open(os.path.join(a.out, 'index.csv'), 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f)
        w.writerow(['name', 'address', 'file'])
        w.writerows(sorted(index))
    with open(os.path.join(a.out, 'INDEX.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Identified functions by class/namespace\n\n| group | functions |\n|---|---|\n')
        for g, items in sorted(groups.items(), key=lambda kv: -len(kv[1])):
            f.write('| %s | %d |\n' % (g, len(items)))
    print('groups: %d, functions: %d -> %s' % (len(groups), len(index), a.out))


if __name__ == '__main__':
    sys.exit(main())
